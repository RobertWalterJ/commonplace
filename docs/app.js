  function startTimer() {
    const bar = $('#qtimer');
    const clock = $('#clock');
    session.startedAt = Date.now();
    if (bar) {
      const fill = bar.querySelector('i');
      bar.classList.remove('low');
      fill.style.transition = 'none';
      fill.style.transform = 'scaleX(1)';
      requestAnimationFrame(() => requestAnimationFrame(() => {
        fill.style.transition = `transform ${QUESTION_MS}ms linear`;
        fill.style.transform = 'scaleX(0)';
      }));
    }
    clearTimeout(tick);
    clearInterval(startTimer._c);
    // A number counting down reads faster than a bar alone, and it is what the
    // other apps in this family show.
    startTimer._c = setInterval(() => {
      const left = remainingMs();
      clock.textContent = `${(left / 1000).toFixed(1)}s`;
      const low = left <= URGENT_MS;
      clock.classList.toggle('low', low);
      if (bar) bar.classList.toggle('low', low);
    }, 100);
    clock.textContent = `${(QUESTION_MS / 1000).toFixed(1)}s`;
    tick = setTimeout(() => answer(-1), QUESTION_MS);
  }

  function stopTimer() {
    clearTimeout(tick);
    clearInterval(startTimer._c);
    clearInterval(revealWords._h);
    clearTimeout(showVerdict._h);
    tick = null;
  }

  function remainingMs() {
    if (!session || !session.mode.timed || !session.startedAt) return 0;
    return Math.max(0, QUESTION_MS - (Date.now() - session.startedAt));
  }

  function answer(choice) {
    const s = session;
    const q = s.questions[s.i];
    if (q.done) return;
    q.done = true;
    const left = remainingMs();
    stopTimer();

    const ok = choice === q.answer;
    q.chose = choice;
    grade(q.item, q.facet, ok);
    if (!ok && choice >= 0) noteConfusion(q, q.options[choice]);

    /* The two options that were neither picked nor correct have done their job
       and are now just noise taking up the room the reveal needs. They collapse
       away, which both makes space and makes the screen visibly resolve to the
       two things that matter: what you said and what was true. */
    $$('#choices .opt').forEach((b, i) => {
      if (i === q.answer) b.classList.add('right');
      else if (i === choice) b.classList.add('wrong');
      else b.classList.add('gone');
      b.onclick = null;
    });
    const ask = $('#stage .ask-line');
    if (ask) ask.hidden = true;

    if (ok) {
      s.correct++; s.streak++; s.best = Math.max(s.best, s.streak);
      s.score += 100 + (s.mode.timed ? Math.round((left / QUESTION_MS) * 60) : 0) + Math.min(s.streak, 8) * 5;
      SFX.correct(s.streak); flash('good'); buzz(12);
    } else {
      s.streak = 0;
      s.misses.push(q);
      SFX.wrong(); flash('bad'); buzz([14, 40, 14]);
      $('#stage').classList.add('shake');
      setTimeout(() => $('#stage').classList.remove('shake'), 340);
    }

    // Show the whole painting once the answer is locked; the crop was the
    // question, not the subject.
    const full = $('#full');
    if (full) { full.style.transition = 'transform .45s ease-out'; full.style.transform = 'scale(1)'; }
    $$('#quote .dim').forEach((d) => d.classList.remove('dim'));
    $('#clock').hidden = true;

    // The clock has done its job; it goes, and the reveal takes its place.
    const bar = $('#qtimer');
    if (bar) bar.hidden = true;

    showReveal(q, ok);

    showVerdict(q, ok);
  }

  /* The reveal. This is the app's actual payload, so it appears in the middle of
     the screen directly under the work — where your eyes already are, having
     just looked at it — rather than behind a button at the bottom that on a
     phone you may never notice. The four options stay put underneath, still
     coloured, so a miss can still see what it picked. */
  function showReveal(q, ok) {
    const el = $('#reveal');
    if (!el) return;
    const item = q.item;
    if (!item) return;

    const head = item.kind === 'art'
      ? `<b>${esc(item.title)}</b><span>${esc([item.artist, yearLabel(item), item.collection].filter(Boolean).join(' · '))}</span>`
      : `<b>${esc(item.cite)}</b><span>${esc([item.speaker, item.stage ? 'stage direction' : ''].filter(Boolean).join(' · '))}</span>`;

    const ref = item.ref && item.ref.length
      ? `<div class="reveal-ref"><b>Where you have met it</b>${item.ref.map((r) =>
          `<span>${esc(r.what)}${r.by ? ` — ${esc(r.by)}` : ''}${r.year ? `, ${r.year}` : ''}</span>`).join('')}</div>`
      : item.idiom
        ? `<div class="reveal-ref"><b>It gave English</b><span>“${esc(item.idiom)}”</span></div>`
        : '';

    el.innerHTML = `<div class="reveal-head ${ok ? 'ok' : 'no'}">${head}</div>
      ${item.why ? `<p class="reveal-why">${esc(item.why)}</p>` : ''}${ref}`;
    el.hidden = false;

    // Engaging with it means you want to dwell — stop the auto-advance.
    el.onclick = () => { clearTimeout(showVerdict._h); $('#v-next')?.classList.remove('counting'); };
    // Long notes on a short screen would otherwise sit below the fold.
    requestAnimationFrame(() => {
      const r = el.getBoundingClientRect();
      if (r.bottom > window.innerHeight - 90) el.scrollIntoView({ block: 'center', behavior: 'smooth' });
    });
  }

  const AFTER_RIGHT_MS = 900;
  const AFTER_WRONG_MS = 2400;   // long enough to see the whole painting and the answer
  const READ_BONUS_MS = 2200;    // extra when the reveal actually has something to read

  function showVerdict(q, ok) {
    const v = $('#verdict');
    const last = session.i >= session.questions.length - 1;
    v.hidden = false;
    v.innerHTML = `<div class="foot two">
      <button class="btn-alt" id="v-card">Full card</button>
      <button class="btn-go" id="v-next">${last ? 'Finish' : 'Next'}</button></div>`;
    $('#choices').classList.add('has-verdict');
    // Opening the card means you want to dwell on this one — stop the clock.
    $('#v-card').onclick = () => { clearTimeout(showVerdict._h); openCard(q.item); };
    $('#v-next').onclick = next;

    /* Advance on a miss too, not only on a correct answer. By this point the
       painting has zoomed out and the right answer is lit, so holding the
       screen until a tap leaves you looking at a finished question — and since
       the verdict bar sits under the options, on a phone it was off-screen
       entirely, which made the round look as if it were stuck waiting for the
       countdown. A miss gets a longer pause than a hit, because there is
       something to look at. */
    clearTimeout(showVerdict._h);
    if (store.settings.auto) {
      // A card with a note to read earns more time than a bare attribution.
      const hasReading = !!(q.item && (q.item.why || q.item.ref || q.item.idiom));
      const wait = (ok ? AFTER_RIGHT_MS : AFTER_WRONG_MS) + (hasReading ? READ_BONUS_MS : 0);
      const nextBtn = $('#v-next');
      // Make the pacing visible rather than something that just happens to you.
      nextBtn.style.setProperty('--count', `${wait}ms`);
      nextBtn.classList.add('counting');
      showVerdict._h = setTimeout(() => { if (!v.hidden) next(); }, wait);
    }
  }

  function next() {
    clearTimeout(showVerdict._h);
    $('#verdict').hidden = true;
    $('#choices').classList.remove('has-verdict');
    session.i++;
    if (session.i >= session.questions.length) finishRound();
    else renderQuestion();
  }

  // ── sequence ────────────────────────────────────────────────────────────
  function renderSequence(q) {
    $('#clock').hidden = true;
    q.picked = [];
    $('#stage').innerHTML = `<p class="ask-line">${esc(q.ask)}</p>
      <div class="order-list" id="order">${q.items.map((it, i) => `
        <button class="order-item" data-i="${i}">
          <span class="pick"></span>
          <span class="otxt">
            <b>${esc(it.kind === 'art' ? it.title : it.work)}</b>
            <span>${esc(it.kind === 'art' ? it.artist : `${it.text[0].slice(0, 38)}…`)}</span>
          </span>
          ${it.kind === 'art'
            ? `<span class="order-thumb"><img src="${thumbSrc(it)}" alt=""></span>` : ''}
        </button>`).join('')}</div>`;
    $('#choices').innerHTML = '';
    $$('#order .order-item').forEach((b) => {
      b.onclick = () => {
        if (q.done) return;
        const i = +b.dataset.i;
        if (q.picked.includes(i)) return;
        q.picked.push(i);
        b.classList.add('picked');
        b.querySelector('.pick').textContent = q.picked.length;
        SFX.tap();
        if (q.picked.length === q.items.length) gradeSequence(q);
      };
    });
  }

  function gradeSequence(q) {
    q.done = true;
    const chosen = q.picked.map((i) => q.items[i]);
    const ok = chosen.every((it, i) => it.year === q.solution[i].year);
    chosen.forEach((it) => grade(it, 'year', ok));
    $$('#order .order-item').forEach((b, i) => {
      const it = q.items[i];
      const rightPlace = q.solution.indexOf(it) === q.picked.indexOf(i);
      b.classList.add(rightPlace ? 'right' : 'wrong');
      b.querySelector('.pick').textContent = q.solution.indexOf(it) + 1;
      const sub = b.querySelector('.otxt span');
      if (sub) sub.textContent = `${sub.textContent} · ${yearLabel(it)}`;
    });
    if (ok) {
      session.correct++; session.streak++;
      session.best = Math.max(session.best, session.streak);
      session.score += 160;
      SFX.correct(session.streak); flash('good'); buzz(12);
    } else {
      session.streak = 0;
      session.misses.push(q);
      SFX.wrong(); flash('bad'); buzz([14, 40, 14]);
    }
    showVerdict({ item: chosen[0] }, ok);
  }

  // ── grading and memory ──────────────────────────────────────────────────
  function grade(item, facet, ok) {
    if (!item || !facet) return;
    const r = rec(item.id, facet);
    const now = Date.now();
    r.n++; r.last = now;
    if (ok) { r.c++; r.box = Math.min(r.box + 1, INTERVALS.length - 1); }
    else { r.box = 0; }
    r.due = now + INTERVALS[r.box];
    saveStore();
  }

  /* Confusion pairs. Recording which wrong answer you gave — not merely that you
     were wrong — is what makes a targeted drill possible later. Only the facets
     where a pair is a real thing are tracked; there is nothing to drill about
     picking the wrong missing word once. */
  function noteConfusion(q, chosen) {
    if (q.facet !== 'artist' && q.facet !== 'work' && q.facet !== 'speaker') return;
    const k = `${q.facet}|${q.options[q.answer]}|${chosen}`;
    store.confuse[k] = (store.confuse[k] || 0) + 1;
    saveStore();
  }

  function confusionPairs() {
    const merged = new Map();
    for (const [k, n] of Object.entries(store.confuse)) {
      const [facet, a, b] = k.split('|');
      const key = [facet, ...[a, b].sort()].join('|');
      const e = merged.get(key) || { facet, a, b, n: 0 };
      e.n += n;
      merged.set(key, e);
    }
    return [...merged.values()].sort((x, y) => y.n - x.n);
  }

  /* A drill is an ordinary round with the pool narrowed to the two things being
     confused, and the decoys forced to be each other. */
  function startDrill(pair) {
    const match = (item, name) =>
      (pair.facet === 'artist' && item.artist === name)
      || (pair.facet === 'work' && item.work === name)
      || (pair.facet === 'speaker' && item.speaker === name);
    const pool = scopedItems().filter((i) => match(i, pair.a) || match(i, pair.b));
    if (pool.length < 4) { toast('Not enough of those two to drill yet.'); return; }
    const m = modeOf(pair.facet === 'artist' ? 'eye' : pair.facet === 'work' ? 'cadence' : 'voices');
    SFX.unlock();
    const questions = sample(pool, Math.min(12, pool.length)).map((item) => {
      const q = buildQuestion(item, pair.facet, m);
      if (!q) return null;
      const right = q.options[q.answer];
      const other = right === pair.a ? pair.b : pair.a;
      if (!q.options.includes(other)) {
        q.options[q.options.findIndex((o, i) => i !== q.answer)] = other;
      }
      return q;
    }).filter(Boolean);
    if (!questions.length) { toast('Could not build that drill.'); return; }
    session = {
      mode: Object.assign({}, m, { timed: false, label: 'Head to head' }),
      questions, i: 0, correct: 0, streak: 0, best: 0, score: 0,
      misses: [], at: Date.now(), drill: pair,
    };
    show('game');
    renderQuestion();
  }

  // ── results ─────────────────────────────────────────────────────────────
  function finishRound() {
    stopTimer();
    const s = session;
    store.sessions.unshift({
      at: s.at, mode: s.mode.id, n: s.questions.length,
      correct: s.correct, score: s.score, best: s.best,
    });
    store.sessions = store.sessions.slice(0, 120);
    saveStore();
    SFX.finish();

    /* Clearing a confusion should visibly clear it. A clean drill drops the
       count so the prompt on the home screen goes away rather than nagging
       forever about something you have now fixed. */
    if (s.drill && s.correct === s.questions.length) {
      for (const k of Object.keys(store.confuse)) {
        const [facet, a, b] = k.split('|');
        if (facet === s.drill.facet && [a, b].every((x) => x === s.drill.a || x === s.drill.b)) {
          delete store.confuse[k];
        }
      }
      saveStore();
    }

    const missed = s.misses.map((q) => {
      const it = q.item || (q.solution && q.solution[0]);
      if (!it) return '';
      const right = q.options ? q.options[q.answer] : 'the right order';
      const said = q.options && q.chose >= 0 ? q.options[q.chose] : 'ran out of time';
      // For a "what is this?" miss the answer already is the title; repeating
      // it underneath reads like a bug.
      const sub = it.kind !== 'art' ? it.cite
        : right === it.title ? it.artist
        : right === it.artist ? it.title
        : `${it.title} — ${it.artist}`;
      return `<button class="miss-row" data-id="${it.id}">
        <span class="miss-thumb">${it.kind === 'art' ? `<img src="${imgSrc(it)}" alt="">` : ''}</span>
        <span class="miss-txt"><b>${esc(right)}</b>
        ${sub ? `<span>${esc(sub)}</span>` : ''}
        <span class="said">you said ${esc(said)}</span></span></button>`;
    }).join('');

    $('#results-body').innerHTML = `
      <div class="score-big"><b>${s.correct}/${s.questions.length}</b>
        <span>${s.score} points${s.best > 2 ? ` · best run ${s.best}` : ''}</span></div>
      ${s.misses.length
        ? `<div class="section-label" style="padding-left:0">Worth another look</div>${missed}`
        : `<p class="empty">Clean round. Nothing to review.</p>`}`;
    $$('#results-body .miss-row').forEach((r) => {
      r.onclick = () => openCard(ITEM.get(r.dataset.id));
    });
    show('results');
  }

  // ── the card ────────────────────────────────────────────────────────────
  /* Where the app actually teaches. The question is only the excuse for getting
     here, so this carries the whole quotation rather than the fragment, what is
     interesting about it, and where you have met it before. */
  function openCard(item) {
    if (!item) return;
    let html = '';
    if (item.kind === 'art') {
      html += `<div class="card-plate"><img src="${imgSrc(item)}" alt="${esc(item.title)}"></div>
        <h2 class="card-title">${esc(item.title)}</h2>
        <p class="card-sub">${esc(item.artist)}${item.year ? ` · ${yearLabel(item)}` : ''}${item.collection ? ` · ${esc(item.collection)}` : ''}</p>`;
    } else {
      const lines = item.poem || item.text;
      const join = item.prose ? ' ' : '<br>';
      const cont = (item.after || []).length && !item.poem
        ? `<span class="cont">${join}${item.after.map(esc).join(join)}</span>` : '';
      html += `<p class="card-quote">${lines.map(esc).join(join)}${cont}</p>
        <p class="card-sub" style="margin-top:12px">${esc(item.cite)}${item.speaker ? ` · ${esc(item.speaker)}` : ''}${item.stage ? ' · stage direction' : ''}</p>`;
    }
    if (item.why) html += `<p class="card-why">${esc(item.why)}</p>`;
    if (item.ref) {
      html += `<div class="card-ref"><b>Where you have met it</b><ul>${item.ref.map((r) =>
        `<li>${esc(r.what)}${[r.by, r.kind, r.year].filter(Boolean).length
          ? ` <span style="color:var(--ink-3)">— ${esc([r.by, r.kind, r.year].filter(Boolean).join(', '))}</span>` : ''}</li>`
      ).join('')}</ul></div>`;
    }
    if (item.idiom) {
      html += `<div class="card-ref"><b>It gave English</b><ul><li>“${esc(item.idiom)}”</li></ul></div>`;
    }
    const bits = facetsFor(item, { facets: null }).map((f) => {
      const r = store.facets[fkey(item.id, f)];
      const state = !r || !r.n ? 'not met' : r.box >= MASTERED_BOX ? 'known' : `${r.c}/${r.n}`;
      return `${FACET_LABEL[f] || f}: <b>${state}</b>`;
    });
    html += `<p class="card-meta">${bits.join(' &nbsp;·&nbsp; ')}<br>
      Source: <b>${esc(item.source)}</b>${item.kind === 'art' && item.movements?.length
        ? ` · ${esc(item.movements.slice(0, 2).join(', '))}` : ''}</p>`;

    $('#sheet-body').innerHTML = html;
    $('#sheet').hidden = false;
  }
  const closeCard = () => { $('#sheet').hidden = true; };

