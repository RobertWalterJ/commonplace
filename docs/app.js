  /* Until the toggle is used, follow the device. Opening a reading app on a
     phone that is in dark mode and getting a sheet of white paper is a bad first
     second, and defaulting to light quietly guarantees it. */
  function resolvedTheme() {
    if (store.settings.theme) return store.settings.theme;
    return window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches
      ? 'dark' : 'light';
  }
  function applyTheme() {
    const t = resolvedTheme();
    document.documentElement.setAttribute('data-theme', t);
    const meta = document.querySelector('meta[name=theme-color]');
    if (meta) meta.setAttribute('content', t === 'dark' ? '#131322' : '#ffffff');
  }

  // ── wiring ──────────────────────────────────────────────────────────────
