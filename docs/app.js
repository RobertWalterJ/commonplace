  // ── sound ───────────────────────────────────────────────────────────────
  /* Synthesised, never sampled: nothing to ship, nothing to cache, works
     offline, every parameter tunable. A run of correct answers walks up a
     pentatonic ladder so success audibly builds, and drops back on a miss. */
  const SFX = (() => {
    let ctx = null, master = null, noise = null;
    const ROOT = 523.25;                                  // C5
    const LADDER = [0, 2, 4, 7, 9, 12, 14, 16, 19, 21, 24, 26];

    function init() {
      if (ctx) return ctx;
      const AC = window.AudioContext || window.webkitAudioContext;
      if (!AC) return null;
      ctx = new AC();
      master = ctx.createGain();
      master.gain.value = 0.85;
      master.connect(ctx.destination);
      const n = Math.floor(ctx.sampleRate * 0.2);
      noise = ctx.createBuffer(1, n, ctx.sampleRate);
      const d = noise.getChannelData(0);
      for (let i = 0; i < n; i++) d[i] = Math.random() * 2 - 1;
      return ctx;
    }
    // Autoplay policy: audio can only start from a gesture, so everything goes
    // through here and resumes a context the browser suspended.
    function ready() {
      if (!store || store.settings.sound === false) return null;
      const c = init();
      if (!c) return null;
      if (c.state === 'suspended') c.resume().catch(() => {});
      return c;
    }
    function tone(freq, { gain = 0.2, dur = 0.18, delay = 0, bend = 0, type = 'sine' } = {}) {
      const c = ready(); if (!c) return;
      const t = c.currentTime + delay;
      const o = c.createOscillator(), g = c.createGain();
      o.type = type;
      o.frequency.setValueAtTime(freq * (1 + bend), t);
      if (bend) o.frequency.exponentialRampToValueAtTime(freq, t + dur * 0.6);
      g.gain.setValueAtTime(0.0001, t);                   // exponential ramps
      g.gain.exponentialRampToValueAtTime(gain, t + 0.004); // cannot reach zero
      g.gain.exponentialRampToValueAtTime(0.0001, t + dur);
      o.connect(g); g.connect(master);
      o.start(t); o.stop(t + dur + 0.02);
    }
    // The crisp part: a few milliseconds of band-passed noise as the attack.
    function click({ gain = 0.07, freq = 2800, dur = 0.016, delay = 0 } = {}) {
      const c = ready(); if (!c) return;
      const t = c.currentTime + delay;
      const s = c.createBufferSource(); s.buffer = noise;
      const bp = c.createBiquadFilter();
      bp.type = 'bandpass'; bp.frequency.value = freq; bp.Q.value = 1.3;
      const g = c.createGain();
      g.gain.setValueAtTime(gain, t);
      g.gain.exponentialRampToValueAtTime(0.0001, t + dur);
      s.connect(bp); bp.connect(g); g.connect(master);
      s.start(t); s.stop(t + dur + 0.01);
    }
    return {
      unlock() { ready(); },
      tap() { click({ gain: 0.04, freq: 3200, dur: 0.012 }); },
      correct(streak) {
        const step = LADDER[Math.min(Math.max(streak - 1, 0), LADDER.length - 1)];
        const f = ROOT * Math.pow(2, step / 12);
        click({ gain: 0.06, freq: 3400, dur: 0.014 });
        tone(f, { gain: 0.24, dur: 0.2, bend: 0.03 });
        tone(f * 2.01, { gain: 0.08, dur: 0.09, delay: 0.005 });
      },
      wrong() {
        click({ gain: 0.05, freq: 800, dur: 0.02 });
        tone(148, { gain: 0.19, dur: 0.18, bend: 0.28 });
      },
      finish() {
        [0, 4, 7, 12].forEach((s, i) =>
          tone(ROOT * Math.pow(2, s / 12), { gain: 0.17, dur: 0.34, delay: i * 0.09 }));
      },
    };
  })();

