  /* Which (item, facet) pairs a mode can ask. Facets are skipped when the item
     does not carry what they need — no speaker, no Voices question. */
  function facetsFor(item, mode) {
    const out = [];
    const want = mode.facets;
    const can = (f) => {
      if (f === 'artist' || f === 'title') return item.kind === 'art';
      if (f === 'work') return item.kind === 'line';
      if (f === 'speaker') return item.kind === 'line' && !!item.speaker;
      if (f === 'cloze') return item.kind === 'line' || item.kind === 'sonnet';
      if (f === 'ref') return titledRefs(item).length > 0;
      return false;
    };
    if (want) { want.forEach((f) => { if (can(f)) out.push(f); }); return out; }
    // Training: everything this item supports.
    ['artist', 'title', 'work', 'speaker', 'cloze', 'ref'].forEach((f) => { if (can(f)) out.push(f); });
    return out;
  }

  function candidatePool(mode) {
    const s = store.settings.scope;
    let items;
    if (mode.domain === 'art') items = artItems();
    else if (mode.domain === 'line') items = lineItems();
    else if (mode.domain === 'verse') items = verseItems();
    else if (mode.domain === 'ref') items = scopedItems().filter((i) => titledRefs(i).length);
    else items = scopedItems();
    if (mode.domain === 'art' && !s.includes('art')) return [];
    if ((mode.domain === 'line' || mode.domain === 'verse') && !s.includes('text')) return [];
    return items;
  }

  // ── scheduling ──────────────────────────────────────────────────────────
  const isDue = (r, now) => r.n === 0 || r.due <= now;
  const overdueBy = (r, now) => (r.n === 0 ? Infinity : now - r.due);

  /* Build the list of (item, facet) questions for a round.

     Adaptive rounds put the most overdue first, then anything never seen, then
     whatever is weakest. Everything else is shuffled — but with one rule that
     matters more than it looks: no two questions from the same item, and never
     two lines from the same scene. Otherwise the Yorick speech supplies two
     questions in a row and the second is free. */
  function pickQuestions(mode, n) {
    const now = Date.now();
    const pool = candidatePool(mode);
    const pairs = [];
    for (const item of pool) {
      for (const facet of facetsFor(item, mode)) pairs.push({ item, facet });
    }
    if (!pairs.length) return [];

    let ordered;
    if (mode.adaptive) {
      const due = [], fresh = [], rest = [];
      for (const p of pairs) {
        const r = rec(p.item.id, p.facet);
        if (r.n === 0) fresh.push(p);
        else if (isDue(r, now)) due.push({ p, over: overdueBy(r, now) });
        else rest.push({ p, weak: r.c / Math.max(r.n, 1) });
      }
      due.sort((a, b) => b.over - a.over);
      rest.sort((a, b) => a.weak - b.weak);
      ordered = [...due.map((x) => x.p), ...shuffle(fresh), ...rest.map((x) => x.p)];
    } else {
      ordered = shuffle(pairs);
    }

    const out = [];
    const usedItems = new Set();
    const usedScenes = new Set();
    for (const p of ordered) {
      if (out.length >= n) break;
      if (usedItems.has(p.item.id)) continue;
      const scene = p.item.kind === 'line' ? `${p.item.workSlug}/${p.item.act}.${p.item.scene}` : null;
      if (scene && usedScenes.has(scene)) continue;
      usedItems.add(p.item.id);
      if (scene) usedScenes.add(scene);
      out.push(p);
    }
    // If the scene rule starved a short pool, top up ignoring it.
    if (out.length < n) {
      for (const p of ordered) {
        if (out.length >= n) break;
        if (usedItems.has(p.item.id)) continue;
        usedItems.add(p.item.id);
        out.push(p);
      }
    }
    return out;
  }

  // ── question construction ───────────────────────────────────────────────
  /* A question is always "four options, one right", whatever the facet, so the
     grading and the whole scheduling layer never have to care which mode is
     running. Only the prompt and the option labels change. */
  function buildQuestion(item, facet, mode) {
    if (facet === 'artist') return qArtist(item);
    if (facet === 'title') return qTitle(item);
    if (facet === 'work') return qWork(item);
    if (facet === 'speaker') return qSpeaker(item);
    if (facet === 'cloze') return qCloze(item);
    if (facet === 'ref') return qRef(item);
    return null;
  }

  function fourOptions(correct, pool, hardFirst) {
    const seen = new Set([correct]);
    const picks = [];
    for (const c of hardFirst) {
      if (picks.length >= 3) break;
      if (!c || seen.has(c)) continue;
      seen.add(c); picks.push(c);
    }
    for (const c of shuffle(pool.slice())) {
      if (picks.length >= 3) break;
      if (!c || seen.has(c)) continue;
      seen.add(c); picks.push(c);
    }
    const options = shuffle([correct, ...picks]);
    return { options, answer: options.indexOf(correct) };
  }

  function qArtist(item) {
    const near = item.near.map((q) => ITEM.get(q)).filter(Boolean);
    const confusable = (ARTIST.get(item.artistKey)?.confuse || [])
      .map((k) => ARTIST.get(k)?.name);
    const hard = [
      ...(store.settings.hard ? confusable : []),
      ...near.map((n) => n.artist),
      ...confusable,
    ];
    const all = ART.items.map((i) => i.artist);
    const { options, answer } = fourOptions(item.artist, all, hard);
    return { kind: 'art', ask: 'Who painted this?', item, options, answer, facet: 'artist' };
  }

  function qTitle(item) {
    const near = item.near.map((q) => ITEM.get(q)).filter(Boolean);
    const hard = near.map((n) => n.title);
    const all = ART.items.map((i) => i.title);
    const { options, answer } = fourOptions(item.title, all, hard);
    return { kind: 'art', ask: 'What is this?', item, options, answer, facet: 'title' };
  }

  function qWork(item) {
    const me = WORK.get(item.workSlug);
    /* Wrong plays that could plausibly hold this line: same genre first, then
       written within a few years. A comedy line offered against three tragedies
       answers itself. */
    const others = TEXT.works.filter((w) => w.slug !== item.workSlug);
    const sameGenre = others.filter((w) => w.genre === me.genre);
    const nearYear = others.filter((w) => me.year && w.year && Math.abs(w.year - me.year) <= 6);
    const hard = shuffle([...sameGenre.filter((w) => nearYear.includes(w)), ...sameGenre]).map((w) => w.title);
    const { options, answer } = fourOptions(me.title, others.map((w) => w.title), hard);
    /* The speaker is hidden here, unlike everywhere else. Printing "Lady
       Macbeth" under a line and then asking which play it is from is not a
       question, it is a label. */
    return { kind: 'line', ask: 'Which play?', item, options, answer, facet: 'work', hideSpeaker: true };
  }

  function qSpeaker(item) {
    const cast = (WORK.get(item.workSlug)?.cast || []).filter((c) => c !== item.speaker);
    const { options, answer } = fourOptions(item.speaker, cast, cast);
    return {
      kind: 'line', ask: `Who says this, in ${item.work}?`, item, options, answer,
      facet: 'speaker', hideSpeaker: true,
    };
  }

  const STOPWORDS = new Set(('the a an and or but of to in on at by for with is are was were be been am '
    + 'not no nor so as if then than that this these those it its i you he she they we my thy your our his '
    + 'her their them him us me do doth dost hath have has had shall will would could should may might must '
    + 'from into upon what which who whom when where how there here now yet all any some more most such'
  ).split(' '));

  function qCloze(item) {
    const lines = item.text;
    /* Blank the word that carries the line. Preference goes to something late
       in the line — in verse that is usually the rhyme or the stress the whole
       line is built towards, so the metre gives you a fighting chance. */
    const flat = lines.join(' ');
    const tokens = [...flat.matchAll(/[A-Za-z][A-Za-z'’-]*/g)];
    const good = tokens.filter((t) => t[0].length >= 4 && !STOPWORDS.has(t[0].toLowerCase()));
    if (!good.length) return null;
    const late = good.filter((t) => t.index > flat.length * 0.45);
    const chosen = (late.length ? late : good)[Math.floor(Math.random() * (late.length ? late.length : good.length))];
    const word = chosen[0];

    const inQuote = new Set(tokens.map((t) => t[0].toLowerCase()));
    const decoys = WORDS.filter((w) =>
      Math.abs(w.length - word.length) <= 2
      && !inQuote.has(w.toLowerCase())
      && !STOPWORDS.has(w.toLowerCase()));
    const { options, answer } = fourOptions(word, decoys, sample(decoys, 8));
    return {
      kind: 'cloze', ask: 'One word is missing.', item, options, answer, facet: 'cloze',
      blankAt: chosen.index, blankLen: word.length,
    };
  }

  /* Some references are not titles — an inscription on a building, a coin, a
     recital at a ceremony. They belong on the card, but "which of these took
     its name from this?" cannot offer them as an option, so questions are built
     only from the ones that name something. */
  const titledRefs = (item) => (item.ref || []).filter((r) => !r.notATitle);

  function qRef(item) {
    const usable = titledRefs(item);
    if (!usable.length) return null;
    const mine = usable[Math.floor(Math.random() * usable.length)];
    const others = scopedItems().filter((i) => titledRefs(i).length && i.id !== item.id);
    // Forward: given the modern thing, name the source. Backward: given the
    // source, name what borrowed it. Both are worth drilling; they fail
    // differently.
    if (Math.random() < 0.5) {
      /* Label the options with the line itself, not the citation. Offering
         "Hamlet 3.1" against "Hamlet 5.1" asks you to tell two scene numbers
         apart, which is not the skill; offering the actual words asks you to
         recognise the source, which is. Decoys are taken one per work so the
         board is never three excerpts from the same play. */
      const label = (i) => (i.kind === 'art'
        ? `${i.title} — ${i.artist}`
        : `“${snippet(i.text.join(' '), 44)}” — ${i.work}`);
      const byWork = new Map();
      for (const o of shuffle(others.slice())) {
        const k = o.kind === 'art' ? o.artistKey : o.workSlug;
        if (k === (item.kind === 'art' ? item.artistKey : item.workSlug)) continue;
        if (!byWork.has(k)) byWork.set(k, o);
      }
      const spread = [...byWork.values()].map(label);
      const pool = others.map(label);
      const { options, answer } = fourOptions(label(item), pool, spread);
      return {
        kind: 'ref-forward', ask: 'Where does this come from?', item, options, answer,
        facet: 'ref', subject: mine,
      };
    }
    const pool = others.flatMap((i) => titledRefs(i).map((r) => r.what));
    const { options, answer } = fourOptions(mine.what, pool, sample(pool, 6));
    return {
      kind: 'ref-back', ask: 'Which of these took its name from this?', item,
      options, answer, facet: 'ref', subject: mine,
    };
  }

  /* Sequence is the one question that is not four options. Four works, tapped
     oldest first, and the gap between adjacent dates is forced wide enough that
     it is a question about the map rather than about a coin toss. */
  function buildSequence() {
    const pool = scopedItems().filter((i) => i.year);
    if (pool.length < 8) return null;
    for (let attempt = 0; attempt < 40; attempt++) {
      const four = sample(pool, 4).sort((a, b) => a.year - b.year);
      const gaps = four.slice(1).map((x, i) => x.year - four[i].year);
      if (gaps.every((g) => g >= 12)) {
        return { kind: 'sequence', ask: 'Oldest first.', items: shuffle(four.slice()), solution: four, facet: 'year' };
      }
    }
    const four = sample(pool, 4).sort((a, b) => a.year - b.year);
    return { kind: 'sequence', ask: 'Oldest first.', items: shuffle(four.slice()), solution: four, facet: 'year' };
  }

