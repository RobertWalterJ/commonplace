  /* Reference of the Day. Deliberately not random: whatever you most recently
     got wrong, because the twenty seconds after a miss is when a card is worth
     most. Failing that, the weakest thing you have seen; failing that, something
     from the curated core you have not met yet. */
  function pickDaily() {
    const today = dayKey(Date.now());
    if (store.daily.day === today && ITEM.has(store.daily.id)) return ITEM.get(store.daily.id);
    const scored = [];
    for (const [k, r] of Object.entries(store.facets)) {
      const id = k.split('#')[0];
      if (!ITEM.has(id)) continue;
      const wrongRate = 1 - r.c / Math.max(r.n, 1);
      if (r.n > 0 && wrongRate > 0) scored.push({ id, s: wrongRate * 10 + r.last / 1e12 });
    }
    scored.sort((a, b) => b.s - a.s);
    let chosen = scored[0] && ITEM.get(scored[0].id);
    if (!chosen) {
      const rich = scopedItems().filter((i) => (i.why || i.ref)
        && !facetsFor(i, { facets: null }).some((f) => store.facets[fkey(i.id, f)]));
      chosen = rich[Math.floor(Math.random() * rich.length)] || scopedItems()[0];
    }
    store.daily = { day: today, id: chosen.id };
    saveStore();
    return chosen;
  }

